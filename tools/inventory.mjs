// @ts-check
//
// Consumer inventory builder: finds files across the owner's account and both
// orgs (projek-xyz, creasico) that call this repo's reusable workflows, parses
// their call sites, and writes `consumers.yml` — untracked scratch state
// (gitignored), refreshed per impact run in CI or via `npm run consumers`
// locally. Hand-maintained entries for repos code search cannot see live in
// the tracked `consumers-manual.yml` and are merged on every refresh.
//
// Caveats (recorded per the design spec):
// - Code search only indexes public repos unless the token has access AND org
//   code-search is enabled; entries for repos search cannot see must be added
//   by hand to consumers-manual.yml — refresh merges them instead of overwriting.
// - The token(s) come from the DEFAULT_PAT env/secret; a classic PAT with
//   `repo` + `workflow` scopes spans all three scopes. Multiple newline- or
//   comma-separated tokens are unioned and deduped (fine-grained PATs are
//   bound to a single resource owner).

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { load } from 'js-yaml';
import { listWorkflowFiles } from './extract-contracts.mjs';

/**
 * @typedef {object} CallSite
 * @property {string} workflow workflow name without extension (e.g. 'prepare')
 * @property {string[]} inputs `with:` input names the call site passes
 * @property {string[]} outputs `needs.<job>.outputs.<name>` values the file reads from this call
 */

/**
 * @typedef {object} Entry
 * @property {string} repo `owner/name`
 * @property {string} path repo-relative path of the calling workflow file
 * @property {boolean} manual preserved across refreshes when true
 * @property {CallSite[]} calls
 */

const WORKFLOW_PATH_RE = /^\.github\/workflows\/[\w.-]+\.ya?ml$/;
const CALL_RE = /projek-xyz\/actions\/\.github\/workflows\/([\w-]+)\.yml/;
const API = 'https://api.github.com';

/**
 * Extract this repo's call sites from a consumer workflow file.
 *
 * @param {string} workflowYaml
 * @param {string} [_repoPath] accepted for caller context; unused
 * @returns {CallSite[]}
 */
export function parseCallSites(workflowYaml, _repoPath = '') {
  /** @type {Record<string, any>} */
  const doc = /** @type {any} */ (load(workflowYaml)) ?? {};
  /** @type {CallSite[]} */
  const calls = [];
  /** @type {Map<string, CallSite>} caller job id → its call site */
  const callByJob = new Map();

  for (const [jobId, job] of Object.entries(doc.jobs ?? {})) {
    const uses = typeof job?.uses === 'string' ? job.uses : '';
    const match = uses.match(CALL_RE);
    if (!match) continue;
    const call = /** @type {CallSite} */ ({
      workflow: match[1],
      inputs: Object.keys(job.with ?? {}),
      outputs: [],
    });
    calls.push(call);
    callByJob.set(jobId, call);
  }

  // Attribute needs.<caller-job>.outputs.<name> reads anywhere in the file to
  // that caller's call site (dot form for the job id, dot or bracket for the name).
  for (const [jobId, call] of callByJob) {
    const escaped = jobId.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const re = new RegExp(`needs\\.${escaped}\\.outputs(?:\\.([A-Za-z0-9_-]+)|\\[\\s*['"]([^'"]+)['"]\\s*\\])`, 'g');
    const found = new Set();
    for (const m of workflowYaml.matchAll(re)) {
      const name = m[1] ?? m[2];
      if (name) found.add(name);
    }
    if (found.size > 0) call.outputs = [...found].sort();
  }

  return calls;
}

/**
 * Merge fresh search results with the previous inventory, preserving manual
 * entries search cannot see. Dedupe key is `repo` + `path`; fresh data wins.
 *
 * @param {Entry[]} prev
 * @param {Entry[]} next
 * @returns {Entry[]}
 */
export function mergeManual(prev, next) {
  const key = (/** @type {Entry} */ e) => `${e.repo}|${e.path}`;
  const seen = new Set(next.map(key));
  const merged = [...next];
  for (const entry of prev) {
    if (entry.manual === true && !seen.has(key(entry))) merged.push(entry);
  }
  return merged;
}

/**
 * Render the committed `consumers.yml` (stable ordering for clean diffs).
 *
 * @param {Entry[]} entries
 * @param {string} updated `YYYY-MM-DD`
 * @returns {string}
 */
export function renderInventoryYaml(entries, updated) {
  const lines = [
    '# generated by tools/inventory.mjs — untracked scratch state (gitignored);',
    '# hand-maintained entries live in consumers-manual.yml and survive refreshes',
    `updated: '${updated}'`,
  ];

  const sorted = [...entries].sort((a, b) => a.repo.localeCompare(b.repo) || a.path.localeCompare(b.path));

  if (sorted.length === 0) {
    lines.push('consumers: []');
    return `${lines.join('\n')}\n`;
  }

  lines.push('consumers:');
  for (const entry of sorted) {
    lines.push(`  - repo: ${entry.repo}`);
    lines.push(`    path: ${entry.path}`);
    lines.push(`    manual: ${entry.manual}`);
    if (entry.calls.length === 0) {
      lines.push('    calls: []');
    } else {
      lines.push('    calls:');
      const calls = [...entry.calls].sort((a, b) => a.workflow.localeCompare(b.workflow));
      for (const call of calls) {
        lines.push(`      - workflow: ${call.workflow}`);
        lines.push(`        inputs: [${call.inputs.join(', ')}]`);
        lines.push(`        outputs: [${(call.outputs ?? []).join(', ')}]`);
      }
    }
  }

  return `${lines.join('\n')}\n`;
}

/**
 * Code-search every token for call sites of each workflow, then fetch and
 * parse each unique hit. Search failures and incomplete result sets (the
 * `incomplete_results` flag or totals beyond GitHub's 1,000-result cap) are
 * logged and reported via `onSearchFailure`, and content fetches try each
 * token in turn before giving up.
 *
 * @param {object} options
 * @param {string[]} options.tokens
 * @param {string[]} options.workflows workflow names without extension
 * @param {typeof fetch} [options.fetchImpl]
 * @param {{ warn: (msg: string) => void }} [options.log]
 * @param {() => void} [options.onSearchFailure] called once per failed or incomplete search request
 * @returns {Promise<Entry[]>}
 */
export async function searchAndCollect({ tokens, workflows, fetchImpl = fetch, log = console, onSearchFailure }) {
  const headers = (/** @type {string} */ token, /** @type {string} */ accept) => ({
    Authorization: `Bearer ${token}`,
    Accept: accept,
    'X-GitHub-Api-Version': '2022-11-28',
  });

  /** @type {Map<string, Entry>} */
  const hits = new Map();

  for (const token of tokens) {
    for (const name of workflows) {
      // Page through the results (100 per page; GitHub serves at most 1,000
      // per query). An incomplete result set must fail the refresh like a
      // failed request, or the inventory silently loses consumers past the cut.
      for (let page = 1; page <= 10; page += 1) {
        const url = new URL(`${API}/search/code`);
        url.searchParams.set('q', `"projek-xyz/actions/.github/workflows/${name}.yml" in:file`);
        url.searchParams.set('per_page', '100');
        url.searchParams.set('page', String(page));

        const res = await fetchImpl(url.toString(), { headers: headers(token, 'application/vnd.github+json') });
        if (!res.ok) {
          log.warn(`code search failed for ${name}: HTTP ${res.status} — skipped`);
          onSearchFailure?.();
          break;
        }
        const data =
          /** @type {{ total_count?: number, incomplete_results?: boolean, items?: { repository?: { full_name?: string }, path?: string }[] }} */ (
            await res.json()
          );
        if (data.incomplete_results === true || (typeof data.total_count === 'number' && data.total_count > 1000)) {
          log.warn(`code search returned incomplete results for ${name} — skipped`);
          onSearchFailure?.();
          break;
        }
        for (const item of data.items ?? []) {
          const repo = item.repository?.full_name;
          const path = item.path;
          if (!repo || !path || !WORKFLOW_PATH_RE.test(path)) continue;
          hits.set(`${repo}|${path}`, { repo, path, manual: false, calls: [] });
        }
        const items = data.items ?? [];
        if (items.length < 100) break;
        if (typeof data.total_count === 'number' && page * 100 >= data.total_count) break;
      }
    }
  }

  /** @type {Entry[]} */
  const entries = [];
  for (const entry of hits.values()) {
    for (let i = 0; i < tokens.length; i += 1) {
      const isLast = i === tokens.length - 1;
      const status = (/** @type {string} */ detail) =>
        isLast ? `${detail} — keeping with calls: []` : `${detail} — trying next token`;
      try {
        const res = await fetchImpl(`${API}/repos/${entry.repo}/contents/${entry.path}`, {
          headers: headers(tokens[i], 'application/vnd.github.raw'),
        });
        if (res.ok) {
          entry.calls = parseCallSites(await res.text(), entry.path);
          break;
        }
        log.warn(`could not fetch ${entry.repo}/${entry.path}: ${status(`HTTP ${res.status}`)}`);
      } catch (err) {
        log.warn(`could not fetch ${entry.repo}/${entry.path}: ${status(String(err))}`);
      }
    }
    entries.push(entry);
  }

  return entries;
}

/**
 * Parse the DEFAULT_PAT env value: one or more newline/comma-separated tokens.
 *
 * @param {string|undefined} raw
 * @returns {string[]}
 */
export function parseTokens(raw) {
  return (raw ?? '')
    .split(/[,\n]/)
    .map((s) => s.trim())
    .filter(Boolean);
}

/**
 * Read existing consumers.yml entries (tolerates a missing file).
 *
 * @param {string} file
 * @returns {Entry[]}
 */
export function readPrevEntries(file) {
  if (!existsSync(file)) return [];
  /** @type {Record<string, any>} */
  const doc = /** @type {any} */ (load(readFileSync(file, 'utf8'))) ?? {};
  if (!Array.isArray(doc.consumers)) return [];
  return doc.consumers.map((/** @type {any} */ e) => ({
    repo: String(e.repo),
    path: String(e.path),
    manual: e.manual === true,
    calls: (Array.isArray(e.calls) ? e.calls : []).map((/** @type {any} */ c) => ({
      workflow: String(c.workflow),
      inputs: Array.isArray(c.inputs) ? c.inputs.map(String) : [],
      outputs: Array.isArray(c.outputs) ? c.outputs.map(String) : [],
    })),
  }));
}

async function main() {
  const tokens = parseTokens(process.env.DEFAULT_PAT);
  if (tokens.length === 0) {
    console.error('DEFAULT_PAT is empty — set it to one or more newline/comma-separated tokens.');
    process.exit(1);
  }

  const workflows = listWorkflowFiles('.github/workflows').map((f) => f.replace(/\.ya?ml$/, ''));
  let searchFailures = 0;
  const next = await searchAndCollect({
    tokens,
    workflows,
    fetchImpl: fetch,
    log: console,
    onSearchFailure: () => {
      searchFailures += 1;
    },
  });

  // Partial-failure guard: a single failed search silently drops every
  // consumer that query would have found. Refuse to write — a failed refresh
  // must not shrink a working inventory; the impact report falls back to its
  // inventory-unavailable warning instead.
  if (searchFailures > 0) {
    console.error(`${searchFailures} code search request(s) failed — refusing to write a partial inventory.`);
    process.exit(1);
  }

  // Hand-maintained entries for repos code search cannot see; everything in
  // the manual file is manual by definition.
  const prev = readPrevEntries('consumers-manual.yml').map((e) => ({ ...e, manual: true }));
  const merged = mergeManual(prev, next);
  const updated = new Date().toISOString().slice(0, 10);
  const rendered = renderInventoryYaml(merged, updated);

  // Skip the write when only the `updated:` date would change, so repeated
  // local runs don't churn the untracked file.
  const contentOnly = (/** @type {string} */ text) =>
    text
      .split('\n')
      .filter((line) => !line.startsWith('updated:'))
      .join('\n')
      .trim();
  const prevText = existsSync('consumers.yml') ? readFileSync('consumers.yml', 'utf8') : '';
  if (contentOnly(prevText) === contentOnly(rendered)) {
    console.log('consumers.yml unchanged — skipping write');
    return;
  }

  writeFileSync('consumers.yml', rendered);
  console.log(`wrote consumers.yml (${merged.length} entries: ${next.length} found, ${merged.length - next.length} manual)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
